namespace EyeCtrl.Core.Keyboard;

/// <summary>Keyboard modifier keys used for modified key presses (e.g., Ctrl+C).</summary>
public enum ModifierKey
{
    /// <summary>Shift key.</summary>
    Shift,
    /// <summary>Control key.</summary>
    Ctrl,
    /// <summary>Alt key.</summary>
    Alt,
    /// <summary>Windows key.</summary>
    Win,
    /// <summary>Caps Lock toggle.</summary>
    CapsLock
}
